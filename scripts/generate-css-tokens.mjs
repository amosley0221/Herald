#!/usr/bin/env node
/**
 * Generates the desktop app's CSS custom properties from `@herald/core/tokens`.
 *
 * The Android app imports those tokens directly; the desktop app needs them as
 * CSS. Generating rather than hand-copying is what keeps the two apps from
 * drifting — change a value in tokens.ts, run this, and both follow.
 *
 *   node scripts/generate-css-tokens.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { color, font, leading, motion, shape, space, text, tracking } from '../packages/core/dist/index.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(root, 'apps/desktop/src/tokens.generated.css');

/** camelCase -> kebab-case, so `goldBright` becomes `--cp-gold-bright`. */
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

const lines = [
  '/*',
  ' * Crowned Pixel tokens.',
  ' *',
  ' * GENERATED by scripts/generate-css-tokens.mjs from packages/core/src/tokens.ts.',
  ' * Do not edit: run the script instead.',
  ' */',
  ':root {',
  '  /* Colour */',
  ...Object.entries(color).map(([name, value]) => `  --cp-${kebab(name)}: ${value};`),
  '',
  '  /* Type */',
  `  --cp-font-display: '${font.display}', Georgia, serif;`,
  `  --cp-font-body: '${font.body}', system-ui, sans-serif;`,
  ...Object.entries(tracking).map(([name, value]) => `  --cp-tracking-${kebab(name)}: ${value}em;`),
  ...Object.entries(text).map(([name, value]) => `  --cp-text-${kebab(name)}: ${value}px;`),
  ...Object.entries(leading).map(([name, value]) => `  --cp-leading-${kebab(name)}: ${value};`),
  '',
  '  /* Space and shape */',
  ...Object.entries(space).map(([step, value]) => `  --cp-space-${step}: ${value}px;`),
  `  --cp-radius: ${shape.radius}px;`,
  `  --cp-hairline: ${shape.hairline}px;`,
  '',
  '  /* Motion */',
  `  --cp-duration: ${motion.duration}ms;`,
  `  --cp-ease: ${motion.ease};`,
  `  --cp-toast-duration: ${motion.toastDuration}ms;`,
  '}',
  '',
];

writeFileSync(target, lines.join('\n'), 'utf8');
console.log(`Wrote ${target.replace(`${root}/`, '')}`);
